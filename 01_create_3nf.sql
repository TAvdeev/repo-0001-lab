
CREATE SCHEMA exam_3nf;

CREATE TABLE exam_3nf.students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE exam_3nf.students IS 'Студенты, готовящиеся к экзаменам';

CREATE TABLE exam_3nf.subjects (
    subject_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name VARCHAR(200) NOT NULL UNIQUE
);
COMMENT ON TABLE exam_3nf.subjects IS 'Справочник учебных дисциплин';

CREATE TABLE exam_3nf.topics (
    topic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id INTEGER NOT NULL REFERENCES exam_3nf.subjects(subject_id),
    topic_name VARCHAR(200) NOT NULL,
    difficulty_level INTEGER NOT NULL CHECK (difficulty_level BETWEEN 1 AND 5),
    CONSTRAINT uq_topic_subject_name UNIQUE (subject_id, topic_name)
);
COMMENT ON TABLE exam_3nf.topics IS 'Темы дисциплин для подготовки';
COMMENT ON COLUMN exam_3nf.topics.difficulty_level IS 'Условная сложность темы от 1 до 5';

CREATE TABLE exam_3nf.exams (
    exam_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id INTEGER NOT NULL REFERENCES exam_3nf.subjects(subject_id),
    exam_name VARCHAR(200) NOT NULL,
    exam_date DATE NOT NULL,
    excellent_threshold INTEGER NOT NULL DEFAULT 90
        CHECK (excellent_threshold BETWEEN 0 AND 100)
);
COMMENT ON TABLE exam_3nf.exams IS 'Экзамены с порогом для отличной оценки';

CREATE TABLE exam_3nf.preparation_plans (
    plan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES exam_3nf.students(student_id),
    exam_id INTEGER NOT NULL REFERENCES exam_3nf.exams(exam_id),
    target_grade INTEGER NOT NULL DEFAULT 5 CHECK (target_grade = 5),
    start_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'planned'
        CHECK (status IN ('planned','in_progress','completed','cancelled'))
);
COMMENT ON TABLE exam_3nf.preparation_plans IS 'Планы подготовки к экзамену с целевой оценкой 5';
COMMENT ON COLUMN exam_3nf.preparation_plans.target_grade IS 'В варианте 1 целевая оценка всегда 5';

CREATE TABLE exam_3nf.plan_steps (
    step_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id INTEGER NOT NULL REFERENCES exam_3nf.preparation_plans(plan_id),
    topic_id INTEGER NOT NULL REFERENCES exam_3nf.topics(topic_id),
    step_order INTEGER NOT NULL CHECK (step_order > 0),
    activity_type VARCHAR(50) NOT NULL
        CHECK (activity_type IN ('theory','practice','review')),
    planned_date DATE NOT NULL,
    planned_hours NUMERIC(5,2) NOT NULL CHECK (planned_hours > 0),
    completed_at TIMESTAMP,
    CONSTRAINT uq_plan_step_order UNIQUE (plan_id, step_order)
);
COMMENT ON TABLE exam_3nf.plan_steps IS 'Упорядоченные этапы подготовки';
COMMENT ON COLUMN exam_3nf.plan_steps.step_order IS 'Номер этапа в рамках конкретного плана';

CREATE TABLE exam_3nf.practice_tests (
    test_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id INTEGER NOT NULL REFERENCES exam_3nf.preparation_plans(plan_id),
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    taken_at TIMESTAMP NOT NULL,
    score_percent NUMERIC(5,2) NOT NULL CHECK (score_percent BETWEEN 0 AND 100),
    CONSTRAINT uq_plan_attempt UNIQUE (plan_id, attempt_no)
);
COMMENT ON TABLE exam_3nf.practice_tests IS 'Промежуточная проверка знаний';

CREATE TABLE exam_3nf.exam_results (
    result_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id INTEGER NOT NULL UNIQUE REFERENCES exam_3nf.preparation_plans(plan_id),
    taken_on DATE NOT NULL,
    score_percent NUMERIC(5,2) NOT NULL CHECK (score_percent BETWEEN 0 AND 100),
    grade INTEGER NOT NULL CHECK (grade BETWEEN 2 AND 5)
);
COMMENT ON TABLE exam_3nf.exam_results IS 'Один итоговый результат для каждого плана подготовки';

-- Индексы по часто используемым внешним ключам; UNIQUE уже создаёт индексы.
CREATE INDEX idx_topics_subject ON exam_3nf.topics(subject_id);
CREATE INDEX idx_exams_subject ON exam_3nf.exams(subject_id);
CREATE INDEX idx_plans_student ON exam_3nf.preparation_plans(student_id);
CREATE INDEX idx_plans_exam ON exam_3nf.preparation_plans(exam_id);
CREATE INDEX idx_steps_topic ON exam_3nf.plan_steps(topic_id);
CREATE INDEX idx_tests_plan_taken ON exam_3nf.practice_tests(plan_id, taken_at DESC);
